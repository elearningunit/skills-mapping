# סוגי שיעור שאינם קורס שמרצה ממפה: תרגילים (מתרגלים), הנחיית תזה, בחינות, רישום
SKIP_TYPES = re.compile(r'^(תרגיל(?!\+מעבדה)|תזה|בחינת גמר|לרישום)')
ACADEMIC = {'ד"ר': 'ד"ר', "פרופ'": "פרופ'", "פרופ' אמריטוס": "פרופ'"}

clean = lambda s: re.sub(r'\s+', ' ', str(s or '')).strip().strip('[]').strip()
ws = openpyxl.load_workbook(SRC, read_only=True)['Default']
it = ws.iter_rows(values_only=True)
for row in it:
    if row and row[0] == 'מחלקה': head = [clean(h) for h in row]; break
ix = {h: head.index(h) for h in ['מחלקה', 'מספר שעור', 'שם שעור', 'סוג שיעור', 'תואר', 'שם משפחה', 'שם פרטי']}

seen, out = set(), []
stats = collections.Counter(); unmapped = collections.Counter(); types = collections.Counter()
for r in it:
    if not r or not any(r): continue
    stats['rows'] += 1
    src = clean(r[ix['מחלקה']])
    dept = DEPT.get(src)
    if not dept: unmapped[src or '(ריק)'] += 1; continue
    t = clean(r[ix['סוג שיעור']])
    if not t or SKIP_TYPES.match(t): types[t or '(ריק)'] += 1; continue
    num, name = clean(r[ix['מספר שעור']]), clean(r[ix['שם שעור']])
    if not name: continue
    first, last = clean(r[ix['שם פרטי']]), clean(r[ix['שם משפחה']])
    lec = '' if ('טרם' in f'{first} {last}' or not (first or last)) else ' '.join(x for x in [ACADEMIC.get(clean(r[ix['תואר']]), ''), first, last] if x)
    k = (dept, num, name, lec)
    if k in seen: continue
    seen.add(k)
    out.append({'מחלקה': dept, 'מספר קורס': num, 'שם קורס': name, 'שם מרצה': lec, 'שם משפחה': last if lec else ''})

with open(OUT, 'w', encoding='utf-8', newline='') as f:
    w = csv.DictWriter(f, fieldnames=['מחלקה', 'מספר קורס', 'שם קורס', 'שם מרצה', 'שם משפחה'])
    w.writeheader(); w.writerows(out)
print(f"rows read: {stats['rows']}, written: {len(out)}")
print('skipped lesson types:', dict(types))
print('departments not mapped (skipped):', dict(unmapped))
